var update = flag.Bool("update", false, "rewrite testdata/permissions.golden")

// TestPermissions writes who may do what, and what each route requires, to
// a golden file, so every change to permissions shows up in review.
func TestPermissions(t *testing.T) {
	t.Parallel()
	store, err := blob.OpenFile(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	_, rs, err := build(Config{ViteURL: "http://localhost:8361", PublicURL: "http://example.test", Blob: store}, testdb.New(t))
	if err != nil {
		t.Fatal(err)
	}

	var b bytes.Buffer
	b.WriteString("# Generated by TestPermissions. go test ./internal/app -update rewrites it.\n")
	section(&b, "Workspace roles (internal/auth/roles.go)", func(w io.Writer) { matrix(w, auth.Workspace) })
	section(&b, "Workspace routes", func(w io.Writer) { routeTable(w, rs.workspace) })
	section(&b, "Platform roles (internal/auth/roles.go)", func(w io.Writer) { matrix(w, auth.Platform) })
	section(&b, "Admin routes, behind open_admin", func(w io.Writer) { routeTable(w, rs.admin) })

	const golden = "testdata/permissions.golden"
	if *update {
		if err := os.WriteFile(golden, b.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err, "(run go test ./internal/app -update)")
	}
	if !bytes.Equal(want, b.Bytes()) {
		t.Errorf("permissions differ from %s (go test ./internal/app -update rewrites it):\n%s", golden, b.String())
	}
}

func section(b *bytes.Buffer, title string, body func(io.Writer)) {
	fmt.Fprintf(b, "\n## %s\n\n", title)
	tw := tabwriter.NewWriter(b, 0, 0, 2, ' ', 0)
	body(tw)
	if err := tw.Flush(); err != nil {
		panic(err)
	}
}

func matrix[R ~string, A ~string](w io.Writer, p *auth.Policy[R, A]) {
	roles := p.Roles()
	head := []string{"action"}
	for _, r := range roles {
		head = append(head, string(r))
	}
	fmt.Fprintln(w, strings.Join(head, "\t"))
	for _, a := range p.Actions() {
		row := []string{string(a)}
		for _, r := range roles {
			row = append(row, map[bool]string{true: "yes", false: "-"}[p.Can(r, a)])
		}
		fmt.Fprintln(w, strings.Join(row, "\t"))
	}
}

// routeTable lists routes by path, then method.
func routeTable(w io.Writer, routes []auth.Route) {
	routes = slices.Clone(routes)
	slices.SortFunc(routes, func(a, b auth.Route) int {
		am, ap, _ := strings.Cut(a.Pattern, " ")
		bm, bp, _ := strings.Cut(b.Pattern, " ")
		return cmp.Or(strings.Compare(ap, bp), strings.Compare(am, bm))
	})
	for _, r := range routes {
		fmt.Fprintf(w, "%s\t%s\n", r.Pattern, r.Action)
	}
}
