var update = flag.Bool("update", false, "rewrite the golden files in testdata")

// TestPermissions writes who may do what to a golden file, so every change
// to permissions shows up in review.
func TestPermissions(t *testing.T) {
	t.Parallel()
	var b bytes.Buffer
	b.WriteString("# Generated by TestPermissions. go test ./internal/app -update rewrites it.\n")
	section(&b, "Workspace roles (internal/auth/roles.go)", func(w io.Writer) { matrix(w, auth.Workspace) })
	section(&b, "Platform roles (internal/auth/roles.go)", func(w io.Writer) { matrix(w, auth.Platform) })
	golden(t, "testdata/permissions.golden", b.Bytes())
}

// TestRoutes writes every route the app serves, and the action each
// workspace and admin route requires, to a golden file.
func TestRoutes(t *testing.T) {
	t.Parallel()
	store, err := blob.OpenFile(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	_, rs, err := build(Config{ViteURL: "http://localhost:8361", PublicURL: "http://example.test", Blob: store}, testdb.New(t))
	if err != nil {
		t.Fatal(err)
	}

	var b bytes.Buffer
	b.WriteString("# Generated by TestRoutes. go test ./internal/app -update rewrites it.\n")
	b.WriteString("# Each section is one mux. A pattern without a method (*) matches any method;\n")
	b.WriteString("# most hand the request on to a mux below, and / answers 404.\n")
	for _, m := range rs.muxes {
		section(&b, m.Name, func(w io.Writer) { routeTable(w, m.Patterns(), rs.actions[m]) })
	}
	golden(t, "testdata/routes.golden", b.Bytes())
}

func golden(t *testing.T, path string, got []byte) {
	t.Helper()
	if *update {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err, "(run go test ./internal/app -update)")
	}
	if !bytes.Equal(want, got) {
		t.Errorf("%s is out of date (go test ./internal/app -update rewrites it):\n%s", path, got)
	}
}

func section(b *bytes.Buffer, title string, body func(io.Writer)) {
	fmt.Fprintf(b, "\n## %s\n\n", title)
	tw := tabwriter.NewWriter(b, 0, 0, 2, ' ', 0)
	body(tw)
	if err := tw.Flush(); err != nil {
		panic(err)
	}
}

func matrix[R ~string, A ~string](w io.Writer, p *auth.Policy[R, A]) {
	roles := p.Roles()
	head := []string{"action"}
	for _, r := range roles {
		head = append(head, string(r))
	}
	fmt.Fprintln(w, strings.Join(head, "\t"))
	for _, a := range p.Actions() {
		row := []string{string(a)}
		for _, r := range roles {
			row = append(row, map[bool]string{true: "yes", false: "-"}[p.Can(r, a)])
		}
		fmt.Fprintln(w, strings.Join(row, "\t"))
	}
}

// routeTable lists patterns by path, then method, with their actions.
func routeTable(w io.Writer, patterns []string, actions map[string]string) {
	split := func(p string) (method, path string) {
		if m, rest, ok := strings.Cut(p, " "); ok {
			return m, rest
		}
		return "*", p
	}
	patterns = slices.Clone(patterns)
	slices.SortFunc(patterns, func(a, b string) int {
		am, ap := split(a)
		bm, bp := split(b)
		return cmp.Or(strings.Compare(ap, bp), strings.Compare(am, bm))
	})
	for _, p := range patterns {
		method, path := split(p)
		fmt.Fprintln(w, strings.TrimRight(method+"\t"+path+"\t"+actions[p], "\t"))
	}
}
