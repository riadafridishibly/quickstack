// Command chromacss writes the code highlighting colors for posts:
// GitHub's light style, and its dark style when the system is dark.
//
//	go run ./internal/markdown/chromacss frontend/src/chroma.css
package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	"github.com/alecthomas/chroma/v2"
	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: chromacss <out.css>")
		os.Exit(2)
	}
	var out bytes.Buffer
	out.WriteString("/* Code highlighting for posts. Generated by internal/markdown/chromacss; don't edit. */\n")
	out.WriteString(rules(styles.Get("github"), ""))
	out.WriteString("\n@media (prefers-color-scheme: dark) {\n")
	out.WriteString(rules(styles.Get("github-dark"), "  "))
	out.WriteString("}\n")
	if err := os.WriteFile(os.Args[1], out.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// rules leaves out the background, which comes from the theme.
func rules(style *chroma.Style, indent string) string {
	var buf bytes.Buffer
	if err := chromahtml.New(chromahtml.WithClasses(true)).WriteCSS(&buf, style); err != nil {
		panic(err)
	}
	var b strings.Builder
	for line := range strings.Lines(buf.String()) {
		if strings.HasPrefix(line, "/* Background */") || strings.HasPrefix(line, "/* PreWrapper */") {
			continue
		}
		b.WriteString(indent + line)
	}
	return b.String()
}
